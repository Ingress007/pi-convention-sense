import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { isAbsolute, relative, resolve, sep } from "node:path";
import { ObserveAnalyzer } from "../dist/src/observe/analyzer.js";
import { detectJavaRole } from "../dist/src/observe/java-analyzer.js";
import { createDefaultConfig } from "../dist/src/runtime/config.js";

const [repositoryArg, outputArg] = process.argv.slice(2);
if (!repositoryArg) {
  console.error("Usage: node scripts/evaluate-java-repository.mjs <repository-root> [output-directory]");
  process.exit(2);
}

const repositoryRoot = resolve(repositoryArg);
const outputDirectory = resolve(outputArg ?? ".tmp/pi-convention-sense/evaluations/java-repository");
const roleTargets = new Map([
  ["controller", 6],
  ["service-impl", 6],
  ["mapper", 4],
  ["request-dto", 4],
  ["response-dto", 4],
  ["service-interface", 2],
]);

function normalized(path) {
  return path.split(sep).join("/");
}

function isInside(root, path) {
  const value = relative(root, path);
  return value === "" || (!value.startsWith(`..${sep}`) && value !== ".." && !isAbsolute(value));
}

function productionJavaFiles(root) {
  const files = [];
  const stack = [root];
  while (stack.length > 0) {
    const directory = stack.pop();
    if (!directory) continue;
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if ([".git", ".pi", "target", "build", "node_modules", "generated"].includes(entry.name)) continue;
      const path = resolve(directory, entry.name);
      if (entry.isDirectory() && !entry.isSymbolicLink()) stack.push(path);
      else if (entry.isFile() && path.endsWith(".java") && normalized(path).includes("/src/main/java/")) files.push(path);
    }
  }
  return files.sort();
}

function quantileSample(paths, count) {
  const ranked = paths
    .map((path) => ({ path, size: statSync(path).size }))
    .sort((a, b) => a.size - b.size || a.path.localeCompare(b.path));
  if (ranked.length <= count) return ranked.map((item) => item.path);
  const selected = new Set();
  for (let index = 0; index < count; index += 1) {
    const position = Math.round((index * (ranked.length - 1)) / Math.max(1, count - 1));
    selected.add(ranked[position].path);
  }
  for (const item of ranked) {
    if (selected.size >= count) break;
    selected.add(item.path);
  }
  return [...selected];
}

function percentile(values, ratio) {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.ceil(sorted.length * ratio) - 1)] ?? 0;
}

function average(values) {
  return values.length === 0 ? 0 : values.reduce((sum, value) => sum + value, 0) / values.length;
}

const allFiles = productionJavaFiles(repositoryRoot);
const generatedFiles = allFiles.filter((path) => {
  const header = readFileSync(path, "utf8").slice(0, 2_000);
  return (
    /[/\\](?:generated|target|build)[/\\]/i.test(path) ||
    /\bGenerated by\b[\s\S]{0,160}\bDO NOT EDIT\b/i.test(header) ||
    /\bDO NOT EDIT\b[\s\S]{0,160}\bgenerated\b/i.test(header)
  );
});
const generatedSet = new Set(generatedFiles);
const byRole = new Map();
for (const path of allFiles) {
  if (generatedSet.has(path)) continue;
  const role = detectJavaRole(path).role;
  const values = byRole.get(role) ?? [];
  values.push(path);
  byRole.set(role, values);
}

const targets = [];
for (const [role, count] of roleTargets) {
  for (const path of quantileSample(byRole.get(role) ?? [], count)) targets.push({ path, role });
}

const analyzer = new ObserveAnalyzer();
const config = createDefaultConfig();
const results = [];
for (const target of targets) {
  const analyzed = analyzer.analyzeTarget(target.path, repositoryRoot, config);
  const snapshot = analyzed.snapshot;
  const candidates = snapshot?.candidates.map((candidate) => ({
    path: normalized(relative(repositoryRoot, candidate.path)),
    score: candidate.score,
    level: candidate.level,
    role: candidate.facts.role,
    module: candidate.scope.module,
    sameRole: candidate.facts.role === snapshot.scope.role,
    sameModule: candidate.scope.module === snapshot.scope.module,
    insideRepository: isInside(repositoryRoot, candidate.path),
    breakdown: candidate.breakdown,
  })) ?? [];
  results.push({
    target: normalized(relative(repositoryRoot, target.path)),
    selectedRole: target.role,
    fileSize: statSync(target.path).size,
    reason: analyzed.reason,
    durationMs: analyzed.durationMs,
    indexedFileCount: analyzed.indexedFileCount,
    consideredCandidateCount: analyzed.consideredCandidateCount,
    scope: snapshot ? `${snapshot.scope.language}:${snapshot.scope.module}:${snapshot.scope.role}` : undefined,
    scopeConfidence: snapshot?.scope.confidence,
    status: snapshot?.status,
    tokenEstimate: snapshot?.tokenEstimate,
    candidates,
    observations: snapshot?.observations.map((observation) => ({
      category: observation.category,
      pattern: observation.pattern,
      support: observation.support,
      samples: observation.samples,
      confidence: observation.confidence,
      status: observation.status,
      evidence: observation.evidence.map((item) => normalized(relative(repositoryRoot, item.path))),
      counterEvidence: observation.counterEvidence.map((item) => normalized(relative(repositoryRoot, item.path))),
    })) ?? [],
  });
}

const candidateRows = results.flatMap((result) => result.candidates);
const durations = results.map((result) => result.durationMs);
const tokens = results.map((result) => result.tokenEstimate ?? 0);
const metrics = {
  repositoryRoot: normalized(repositoryRoot),
  generatedAt: new Date().toISOString(),
  productionJavaFileCount: allFiles.length,
  generatedFileCount: generatedFiles.length,
  selectedTargetCount: results.length,
  selectedByRole: Object.fromEntries(
    [...roleTargets.keys()].map((role) => [role, results.filter((result) => result.selectedRole === role).length]),
  ),
  validSnapshotCount: results.filter((result) => result.status === "valid").length,
  weakSnapshotCount: results.filter((result) => result.status === "weak").length,
  analysisFailureCount: results.filter((result) => !result.status).length,
  candidateCount: candidateRows.length,
  crossRepositoryCandidateViolationCount: candidateRows.filter((candidate) => !candidate.insideRepository).length,
  sameRoleCandidateRate: candidateRows.length === 0 ? 0 : candidateRows.filter((candidate) => candidate.sameRole).length / candidateRows.length,
  sameModuleCandidateRate: candidateRows.length === 0 ? 0 : candidateRows.filter((candidate) => candidate.sameModule).length / candidateRows.length,
  averageCandidateCount: average(results.map((result) => result.candidates.length)),
  highObservationCount: results.flatMap((result) => result.observations).filter((item) => item.confidence === "high").length,
  mediumObservationCount: results.flatMap((result) => result.observations).filter((item) => item.confidence === "medium").length,
  mixedObservationCount: results.flatMap((result) => result.observations).filter((item) => item.status === "mixed").length,
  firstAnalysisDurationMs: durations[0] ?? 0,
  averageAnalysisDurationMs: average(durations),
  p95AnalysisDurationMs: percentile(durations, 0.95),
  averageSnapshotTokens: average(tokens),
  p95SnapshotTokens: percentile(tokens, 0.95),
};

const reviewQueue = results
  .filter((result) =>
    result.status !== "valid" ||
    result.candidates.some((candidate) => !candidate.sameModule || candidate.level > 1) ||
    result.observations.some((observation) => observation.confidence === "high" && observation.status === "mixed"),
  )
  .map((result) => ({
    target: result.target,
    status: result.status,
    scope: result.scope,
    candidates: result.candidates.map((candidate) => candidate.path),
    reasons: [
      ...(result.status !== "valid" ? [`snapshot:${result.status ?? result.reason ?? "missing"}`] : []),
      ...(result.candidates.some((candidate) => !candidate.sameModule) ? ["cross-module-candidate"] : []),
      ...(result.candidates.some((candidate) => candidate.level > 1) ? ["expanded-search-level"] : []),
      ...(result.observations.some((item) => item.confidence === "high" && item.status === "mixed")
        ? ["high-mixed-observation"]
        : []),
    ],
  }));

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(
  resolve(outputDirectory, "baseline.json"),
  `${JSON.stringify({ metrics, results, reviewQueue }, null, 2)}\n`,
);

const lines = [
  "# Java repository evaluation baseline",
  "",
  `- Repository: \`${metrics.repositoryRoot}\``,
  `- Generated: ${metrics.generatedAt}`,
  `- Production Java files: ${metrics.productionJavaFileCount}`,
  `- Generated files excluded from selection: ${metrics.generatedFileCount}`,
  `- Selected targets: ${metrics.selectedTargetCount}`,
  `- Snapshots valid/weak/failure: ${metrics.validSnapshotCount}/${metrics.weakSnapshotCount}/${metrics.analysisFailureCount}`,
  `- Candidates inside repository violations: ${metrics.crossRepositoryCandidateViolationCount}`,
  `- Same-role candidate rate: ${(metrics.sameRoleCandidateRate * 100).toFixed(1)}%`,
  `- Same-module candidate rate: ${(metrics.sameModuleCandidateRate * 100).toFixed(1)}%`,
  `- Analysis duration first/average/p95: ${metrics.firstAnalysisDurationMs}/${metrics.averageAnalysisDurationMs.toFixed(1)}/${metrics.p95AnalysisDurationMs} ms`,
  `- Snapshot tokens average/p95: ${metrics.averageSnapshotTokens.toFixed(1)}/${metrics.p95SnapshotTokens}`,
  `- High/Medium/Mixed observations: ${metrics.highObservationCount}/${metrics.mediumObservationCount}/${metrics.mixedObservationCount}`,
  `- Manual review queue: ${reviewQueue.length}`,
  "",
  "## Targets",
  "",
  "| Target | Role | Scope | Status | Peers | ms | tokens |",
  "| --- | --- | --- | --- | ---: | ---: | ---: |",
  ...results.map((result) =>
    `| ${result.target} | ${result.selectedRole} | ${result.scope ?? result.reason ?? "-"} | ${result.status ?? "failed"} | ${result.candidates.length} | ${result.durationMs} | ${result.tokenEstimate ?? 0} |`,
  ),
  "",
  "## Manual review queue",
  "",
  ...(reviewQueue.length === 0
    ? ["None."]
    : reviewQueue.map((item) => `- \`${item.target}\`: ${item.reasons.join(", ")}`)),
  "",
];
writeFileSync(resolve(outputDirectory, "baseline.md"), lines.join("\n"));

console.log(JSON.stringify({ metrics, reviewQueue }, null, 2));
